/**
 * Generates k6 performance thresholds from a feature's nfr.md, so the performance gate tests
 * exactly the numbers the product owner agreed to — not a guessed target. Parses the numeric NFR
 * lines (latency percentile, throughput, availability) and emits a k6 thresholds object + options.
 */

export interface PerfThresholds {
  /** e.g. { "http_req_duration{expected_response:true}": ["p(95)<300"] } */
  readonly thresholds: Record<string, string[]>;
  /** Target arrival rate (RPS) if stated. */
  readonly targetRps: number | null;
  readonly notes: string[];
}

const P_LATENCY = /p\s*\(?(\d{2,3})\)?\s*(?:latency|response(?:\s*time)?)?\s*[<≤]\s*(\d+(?:\.\d+)?)\s*(ms|s)/i;
const LATENCY_ALT = /(?:latency|response(?:\s*time)?)[^<≤]*p\s*\(?(\d{2,3})\)?[^<≤]*[<≤]\s*(\d+(?:\.\d+)?)\s*(ms|s)/i;
const RPS = /(\d+(?:\.\d+)?)\s*(rps|tps|req\/s|requests?\/s(?:ec)?)/i;
const ERROR_RATE = /error\s*rate\s*[<≤]\s*(\d+(?:\.\d+)?)\s*%/i;
const AVAIL = /availability\s*(?:>=|≥|>)?\s*(\d+(?:\.\d+)?)\s*%/i;

export function parseNfrPerf(nfr: string): PerfThresholds {
  const thresholds: Record<string, string[]> = {};
  const notes: string[] = [];
  let targetRps: number | null = null;

  const durations: string[] = [];
  for (const line of nfr.split("\n")) {
    const lat = P_LATENCY.exec(line) ?? LATENCY_ALT.exec(line);
    if (lat) {
      const pct = Number(lat[1]);
      const ms = lat[3]?.toLowerCase() === "s" ? Number(lat[2]) * 1000 : Number(lat[2]);
      durations.push(`p(${pct})<${ms}`);
    }
    const rps = RPS.exec(line);
    if (rps && targetRps === null) {
      targetRps = Number(rps[1]);
    }
    const err = ERROR_RATE.exec(line);
    if (err) {
      thresholds["http_req_failed"] = [`rate<${Number(err[1]) / 100}`];
    }
    const avail = AVAIL.exec(line);
    if (avail && !thresholds["http_req_failed"]) {
      // Availability target implies an error-rate ceiling.
      thresholds["http_req_failed"] = [`rate<${Number(((100 - Number(avail[1])) / 100).toPrecision(4))}`];
      notes.push(`Derived error-rate ceiling from ${avail[1]}% availability.`);
    }
  }
  if (durations.length > 0) {
    thresholds["http_req_duration{expected_response:true}"] = durations;
  }
  if (!thresholds["http_req_failed"]) {
    thresholds["http_req_failed"] = ["rate<0.01"];
    notes.push("No explicit error/availability target; defaulted to <1% failures.");
  }
  if (Object.keys(thresholds).length === 0 || durations.length === 0) {
    notes.push("No numeric latency target found in nfr.md; add one (e.g. 'p95 < 300 ms at 200 RPS').");
  }
  return { thresholds, targetRps, notes };
}

/** Emits a runnable k6 options block (constant-arrival-rate when an RPS target is present). */
export function toK6Options(perf: PerfThresholds): string {
  const scenario = perf.targetRps
    ? {
        load: {
          executor: "constant-arrival-rate",
          rate: perf.targetRps,
          timeUnit: "1s",
          duration: "1m",
          preAllocatedVUs: Math.max(10, perf.targetRps),
          maxVUs: perf.targetRps * 4,
        },
      }
    : undefined;
  const options: Record<string, unknown> = { thresholds: perf.thresholds };
  if (scenario) {
    options.scenarios = scenario;
  }
  return `// Generated by eco-forge from nfr.md — do not edit by hand.\nexport const options = ${JSON.stringify(options, null, 2)};\n`;
}
