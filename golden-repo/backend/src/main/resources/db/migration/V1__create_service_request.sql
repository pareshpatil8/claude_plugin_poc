-- Written for Oracle first; also runs on H2 in Oracle mode for the AI-environment profile.
-- ${id_type} is NUMBER(19) on Oracle and BIGINT on H2, where NUMBER maps to NUMERIC and fails
-- Hibernate schema validation for Long ids.
CREATE TABLE service_request (
    id              ${id_type} GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference       VARCHAR2(20)   NOT NULL,
    applicant_name  VARCHAR2(200)  NOT NULL,
    applicant_email VARCHAR2(320)  NOT NULL,
    category        VARCHAR2(30)   NOT NULL,
    description     VARCHAR2(2000),
    status          VARCHAR2(20)   NOT NULL,
    created_by      VARCHAR2(200)  NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_service_request_reference UNIQUE (reference)
);

CREATE INDEX ix_service_request_created_by ON service_request (created_by);
